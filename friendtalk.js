  // Людина по пояс: волосся, обличчя з очима, бровами, носом і ротом, кофта з тінню, руки на колінах.
  function person(cx, base, p, o) {
    cx = Math.round(cx);
    const skinD = shade(p.S, -0.18), GD = shade(p.G, -0.22), GL = shade(p.G, 0.18), HD = shade(p.H, -0.25);
    const head = [9, 13, 15, 17, 17, 17, 17, 17, 17, 17, 17, 16, 16, 15, 13, 11, 9];   // ширина обличчя по рядках
    const hy = base - 70;                                                               // верх голови
    // Довге волосся позаду голови, на плечі.
    // Починається там, де голова вже широка, і заокруглене зверху — інакше голова виходить квадратною.
    if (p.f) {
      for (let i = 0; i < 34; i++) {
        const half = i < 4 ? 8 + i * 0.75 : i < 28 ? 11 : 11 - (i - 28) * 0.6, y = hy + 5 + i;
        R(cx - Math.round(half) - 1, y, Math.round(half) * 2 + 2, 1, OL);
      }
      for (let i = 1; i < 33; i++) {
        const half = i < 4 ? 8 + i * 0.75 - 1 : i < 28 ? 10 : 10 - (i - 28) * 0.6, y = hy + 5 + i;
        R(cx - Math.round(half), y, Math.round(half) * 2, 1, p.H);
      }
      R(cx - 10, hy + 20, 3, 15, HD); R(cx + 7, hy + 20, 3, 15, HD);
    }
    // Тулуб: кофта з округлими плечима.
    // Шия довга, щоб голова не сиділа прямо на плечах.
    // Шия: під підборіддям тінь, донизу світлішає до кольору шкіри — щоб плавно переходила в декольте.
    R(cx - 4, hy + 17, 8, 13, OL); R(cx - 3, hy + 17, 6, 13, skinD);
    R(cx - 3, hy + 22, 6, 8, shade(p.S, -0.08)); R(cx - 2, hy + 24, 4, 6, p.S);
    const ty = base - 48;
    // Плечі похилі: вгорі вужче, донизу ширше.
    const rows = 48;
    for (let r = 0; r < rows; r++) {
      const half = r < 6 ? 9 + r * 1.5 : r < 40 ? 18 : 18 - (r - 40) * 0.5;
      // Верхній контур не перетинає шию — інакше вона наче відрізана.
      if (r === 0) { R(cx - half - 1, ty, half - 4, 1, OL); R(cx + 5, ty, half - 4, 1, OL); continue; }
      R(cx - half - 1, ty + r, half * 2 + 2, 1, OL);
    }
    for (let r = 1; r < rows - 1; r++) {
      const half = r < 6 ? 9 + r * 1.5 - 1 : r < 40 ? 17 : 17 - (r - 40) * 0.5;
      R(cx - half, ty + r, half * 2, 1, p.G);
      R(cx - half, ty + r, 2, 1, GL);                                       // світло з вікна
      R(cx + half - 4, ty + r, 4, 1, GD);                                   // тінь
    }
    if (!p.outfit) { R(cx - 5, ty + 1, 10, 3, GD); R(cx - 3, ty + 1, 6, 2, skinD); }   // комір (з одягом — свій виріз)
    // Одяг за характером.
    outfit(cx, ty, p, GD, GL, skinD);
    R(cx - 15, ty + 10, 1, 26, GD); R(cx + 14, ty + 10, 1, 26, GD);         // лінія рукавів
    // Руки на колінах.
    R(cx - 15, base - 13, 30, 7, OL); R(cx - 14, base - 12, 28, 5, GD);
    R(cx - 7, base - 12, 5, 4, p.S); R(cx + 2, base - 12, 5, 4, p.S);
    // Голова з контуром.
    head.forEach((w, i) => R(cx - Math.ceil(w / 2) - 1, hy + 2 + i, w + 2, 1, OL));
    R(cx - 4, hy + 1, 9, 1, OL);
    head.forEach((w, i) => R(cx - Math.floor(w / 2), hy + 2 + i, w, 1, p.S));
    R(cx - 9, hy + 8, 1, 4, p.S); R(cx + 9, hy + 8, 1, 4, p.S);           // вуха
    R(cx + 5, hy + 4, 3, 12, skinD);                                        // тінь на щоці
    // Волосся зверху.
    R(cx - 8, hy + 1, 17, 4, p.H); R(cx - 6, hy, 13, 1, p.H);
    if (p.f) { R(cx - 9, hy + 3, 3, 11, p.H); R(cx + 7, hy + 3, 3, 11, p.H); R(cx - 4, hy + 4, 6, 2, p.H); }
    else { R(cx - 9, hy + 3, 2, 5, p.H); R(cx + 8, hy + 3, 2, 5, p.H); R(cx - 2, hy + 4, 8, 1, p.H); }
    R(cx - 7, hy + 1, 5, 1, shade(p.H, 0.25));                              // відблиск на волоссі
    // Брови, очі, ніс, рум’янець, рот.
    const ey = hy + 9;
    R(cx - 6, ey - 2, 3, 1, HD); R(cx + 3, ey - 2, 3, 1, HD);
    const blink = (Math.floor(o.t * 1.1 + o.seed) % 6 === 0) && ((o.t * 1.1 + o.seed) % 1 < 0.14);
    if (blink) { R(cx - 6, ey + 1, 3, 1, '#2a1a14'); R(cx + 3, ey + 1, 3, 1, '#2a1a14'); }
    else {
      R(cx - 6, ey, 3, 2, '#f4f1ea'); R(cx + 3, ey, 3, 2, '#f4f1ea');
      R(cx - 5, ey, 2, 2, '#2a1a14'); R(cx + 3, ey, 2, 2, '#2a1a14');
    }
    R(cx, ey + 3, 1, 2, skinD);
    R(cx - 7, ey + 4, 2, 1, '#e8938a'); R(cx + 5, ey + 4, 2, 1, '#e8938a');
    const open = o.talking && Math.floor(o.t * 9) % 2 === 0;
    if (open) { R(cx - 2, ey + 6, 5, 2, '#5a1f1f'); R(cx - 1, ey + 7, 3, 1, '#c45a5a'); }
    else R(cx - 2, ey + 6, 5, 1, p.lips || '#9a4a40');
    if (p.lips && open) R(cx - 2, ey + 6, 5, 1, p.lips);
    if (p.lashes) { R(cx - 7, ey - 1, 1, 1, '#2a1a14'); R(cx + 6, ey - 1, 1, 1, '#2a1a14'); }
    if (p.blush) { R(cx - 8, ey + 4, 3, 2, '#e8938a'); R(cx + 5, ey + 4, 3, 2, '#e8938a'); }
    // Борода й кущисті брови Дідуслава.
    if (p.beard) {
      R(cx - 8, ey + 5, 17, 6, p.beard); R(cx - 6, ey + 11, 13, 3, p.beard); R(cx - 3, ey + 14, 7, 2, p.beard);
      R(cx - 3, ey + 6, 7, 2, shade(p.beard, -0.2));
      if (open) R(cx - 2, ey + 7, 5, 1, '#5a1f1f');
      R(cx - 7, ey - 3, 5, 2, p.brows); R(cx + 3, ey - 3, 5, 2, p.brows);
    }
    // Окуляри Андрія: великі вейфарери — товста верхня оправа, лінзи з темним переливом, відблиск, дужки до волосся.
    if (p.shades) {
      const F = '#0d0d10', L1 = '#1c2733', L2 = '#24384a', L3 = '#30506a', GL = '#a9c3d6';
      for (const lx of [cx - 8, cx + 2]) {
        R(lx, ey - 2, 7, 2, F);                                                   // товста верхня оправа
        R(lx, ey, 7, 1, L1); R(lx, ey + 1, 7, 1, L2); R(lx + 1, ey + 2, 5, 1, L3);  // лінза темнішає догори
        R(lx, ey, 1, 3, F); R(lx + 6, ey, 1, 3, F); R(lx + 1, ey + 3, 5, 1, F);   // боки й низ, скруглений
        R(lx + 1, ey, 2, 1, GL); R(lx + 1, ey + 1, 1, 1, GL);                    // відблиск
      }
      R(cx - 1, ey - 1, 3, 1, F);                                                 // місток
      R(cx - 10, ey - 2, 2, 1, F); R(cx + 9, ey - 2, 2, 1, F);                    // дужки
    }
    // Віночок Одарки.
    if (p.wreath) {
      const fl = ['#e2584a', '#f2d36b', '#6fcf8a', '#7ab0e8', '#e2584a', '#f2d36b'];
      for (let k = 0; k < 6; k++) { R(cx - 9 + k * 3.4, hy - 1 + (k % 2), 3, 3, fl[k]); }
      R(cx - 9, hy + 2, 19, 1, '#3f7a3a');
    }
    return { x: cx * 2, y: hy * 2 };
  }

